-- Open Finance sem servidor próprio: bancos conectados (itens do Meu Pluggy) por usuário,
-- segredo para o agendamento e cron que chama a Edge Function sync-banks a cada 6 horas.

-- ---------- bancos conectados ----------
create table public.open_finance_items (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  item_id text not null,
  name text,
  status text,
  last_synced_at timestamptz,
  last_report text,
  last_error text,
  created_at timestamptz not null default now(),
  unique (user_id, item_id)
);
create index on public.open_finance_items (user_id);

alter table public.open_finance_items enable row level security;
revoke all on public.open_finance_items from anon;
grant select, insert, update, delete on public.open_finance_items to authenticated;
create policy "owner_all" on public.open_finance_items for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

comment on table public.open_finance_items is 'Bancos conectados via Open Finance (um item do Pluggy por banco). A Edge Function sync-banks importa as transações.';

-- ---------- segredo compartilhado entre o cron e a Edge Function ----------
-- Guardado no Vault; a função lê pelo RPC abaixo (só o service_role pode chamar).
do $$
begin
  if not exists (select 1 from vault.secrets where name = 'sync_banks_secret') then
    perform vault.create_secret(encode(gen_random_bytes(32), 'hex'), 'sync_banks_secret', 'Autentica o pg_cron na Edge Function sync-banks');
  end if;
end $$;

create or replace function public.sync_banks_secret()
returns text
language sql
security definer
set search_path = ''
as $$
  select decrypted_secret from vault.decrypted_secrets where name = 'sync_banks_secret' limit 1
$$;
revoke all on function public.sync_banks_secret() from public, anon, authenticated;
grant execute on function public.sync_banks_secret() to service_role;

-- ---------- agendamento ----------
create extension if not exists pg_cron with schema pg_catalog;
create extension if not exists pg_net with schema extensions;

select cron.unschedule(jobid) from cron.job where jobname = 'sync-banks';
select cron.schedule(
  'sync-banks',
  '15 */6 * * *',
  $$
  select net.http_post(
    url := 'https://wenjxwdxsdvmfmmaschn.supabase.co/functions/v1/sync-banks',
    headers := jsonb_build_object(
      'content-type', 'application/json',
      'x-sync-secret', (select decrypted_secret from vault.decrypted_secrets where name = 'sync_banks_secret')
    ),
    body := '{"origem":"cron"}'::jsonb,
    timeout_milliseconds := 300000
  );
  $$
);
