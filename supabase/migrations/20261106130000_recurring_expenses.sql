-- Despesas fixas/recorrentes (aluguel, internet, academia...) com dia de vencimento
create table public.recurring_expenses (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null,
  amount numeric(14, 2) not null check (amount >= 0),
  due_day smallint not null check (due_day between 1 and 31),
  category_id bigint references public.categories (id) on delete set null,
  account_id bigint references public.accounts (id) on delete set null,
  color text not null default '#ff5c7a',
  notes text,
  active boolean not null default true,
  start_date date,
  end_date date,
  created_at timestamptz not null default now()
);
create index on public.recurring_expenses (user_id);
create index on public.recurring_expenses (category_id);
create index on public.recurring_expenses (account_id);

alter table public.recurring_expenses enable row level security;
revoke all on public.recurring_expenses from anon;
grant select, insert, update, delete on public.recurring_expenses to authenticated;
create policy "owner_all" on public.recurring_expenses for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

-- lançamento que paga uma despesa fixa naquele mês
alter table public.transactions
  add column recurring_expense_id bigint references public.recurring_expenses (id) on delete set null;
create index on public.transactions (recurring_expense_id);
