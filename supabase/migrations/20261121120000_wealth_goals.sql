-- Metas de patrimônio por idade, com checkpoint em cada aniversário.
-- Regra: aos N anos, patrimônio líquido >= reserva de emergência + múltiplo × salário anual.
-- Os aniversários entre os marcos (25, 30, 40, 50 por padrão) recebem um múltiplo interpolado ano a ano.
-- Antes do primeiro marco, a meta sai do patrimônio no dia em que a regra começou (start_net_worth).

-- ---------- a regra (uma por usuário) ----------
create table public.wealth_goals (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade unique,
  birth_date date not null,
  emergency_reserve numeric(14, 2) not null default 10000 check (emergency_reserve >= 0),
  annual_salary numeric(14, 2) check (annual_salary is null or annual_salary >= 0),
  start_date date not null default current_date,
  start_net_worth numeric(16, 2),
  anchors jsonb not null default '[{"age":25,"multiple":1.5},{"age":30,"multiple":4},{"age":40,"multiple":12},{"age":50,"multiple":30}]'::jsonb,
  created_at timestamptz not null default now()
);

comment on table public.wealth_goals is 'Regra de patrimônio por idade: reserva de emergência + múltiplo do salário anual em cada marco (anchors).';
comment on column public.wealth_goals.annual_salary is 'Salário anual usado na regra; null = soma das fontes CLT/PJ ativas × 12';
comment on column public.wealth_goals.start_net_worth is 'Patrimônio líquido no dia em que a regra começou (ponto de partida até o primeiro marco)';
comment on column public.wealth_goals.anchors is 'Marcos [{age, multiple}]: aos <age> anos, reserva + <multiple> × salário anual';

-- ---------- resultado de cada checkpoint (aniversário) ----------
create table public.wealth_checkpoints (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  date date not null,
  age integer not null,
  target numeric(16, 2) not null,
  annual_salary numeric(14, 2),
  net_worth numeric(16, 2),
  met boolean,
  hit_early_at date,
  evaluated_at timestamptz,
  celebrated_at timestamptz,
  created_at timestamptz not null default now(),
  unique (user_id, date)
);

comment on table public.wealth_checkpoints is 'Checkpoints avaliados: meta do dia, patrimônio no dia, se bateu e quando foi comemorado.';
comment on column public.wealth_checkpoints.hit_early_at is 'Dia em que o patrimônio passou da meta antes da data do checkpoint';

-- ---------- segurança ----------
do $$
declare
  t text;
begin
  foreach t in array array['wealth_goals', 'wealth_checkpoints'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
    execute format(
      'create policy "owner_all" on public.%I for all to authenticated
         using (user_id = (select auth.uid()))
         with check (user_id = (select auth.uid()))',
      t
    );
  end loop;
end
$$;
