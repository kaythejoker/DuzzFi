-- Cotação automática de renda variável.
-- Cada investimento pode ter posições (ticker + quantidade). A Edge Function update-quotes busca a
-- cotação de cada ticker (Yahoo Finance, com atraso de ~15 min), guarda o último preço na posição e
-- grava quantidade × cotação como valor de mercado do dia (investment_snapshots).

-- ---------- posições ----------
create table public.investment_holdings (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  investment_id bigint not null references public.investments (id) on delete cascade,
  ticker text not null check (ticker = upper(btrim(ticker)) and length(ticker) between 1 and 20),
  quantity numeric(18, 6) not null check (quantity >= 0),
  last_price numeric(14, 4),
  priced_at date,
  quote_error text,
  created_at timestamptz not null default now(),
  unique (investment_id, ticker)
);
create index on public.investment_holdings (user_id);

alter table public.investment_holdings enable row level security;
revoke all on public.investment_holdings from anon;
grant select, insert, update, delete on public.investment_holdings to authenticated;
create policy "owner_all" on public.investment_holdings for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

comment on table public.investment_holdings is 'Posições (ticker + quantidade) de um investimento. A Edge Function update-quotes atualiza last_price/priced_at e grava o valor de mercado em investment_snapshots.';
comment on column public.investment_holdings.ticker is 'Código na B3 (ITSA4, LVBI11). Outros códigos são passados ao Yahoo Finance como estão.';
comment on column public.investment_holdings.quote_error is 'Último erro ao buscar a cotação deste ticker (null quando a última busca deu certo)';

-- ---------- agendamento ----------
-- Dias úteis às 21:30 UTC (18:30 em Brasília), depois do fechamento do pregão.
-- Reaproveita o segredo do Vault usado pela sync-banks (sync_banks_secret).
select cron.unschedule(jobid) from cron.job where jobname = 'update-quotes';
select cron.schedule(
  'update-quotes',
  '30 21 * * 1-5',
  $$
  select net.http_post(
    url := 'https://wenjxwdxsdvmfmmaschn.supabase.co/functions/v1/update-quotes',
    headers := jsonb_build_object(
      'content-type', 'application/json',
      'x-sync-secret', (select decrypted_secret from vault.decrypted_secrets where name = 'sync_banks_secret')
    ),
    body := '{"origem":"cron"}'::jsonb,
    timeout_milliseconds := 120000
  );
  $$
);
