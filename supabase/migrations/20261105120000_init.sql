-- DuzzFinance: schema inicial
-- Todas as tabelas pertencem a um usuário (auth.users) e são protegidas por RLS:
-- cada usuário só lê e escreve as próprias linhas.

-- ---------- contas ----------
create table public.accounts (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null,
  type text not null check (type in ('checking', 'savings', 'credit_card', 'cash', 'wallet', 'other')),
  institution text,
  color text not null default '#8a00ff',
  initial_balance numeric(14, 2) not null default 0,
  archived boolean not null default false,
  created_at timestamptz not null default now()
);

-- ---------- categorias ----------
create table public.categories (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null,
  type text not null check (type in ('expense', 'income')),
  color text not null default '#8a00ff',
  icon text,
  budget numeric(14, 2) check (budget is null or budget >= 0),
  keywords text[] not null default '{}',
  archived boolean not null default false,
  created_at timestamptz not null default now()
);

-- ---------- fontes de renda ----------
create table public.income_sources (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null,
  type text not null check (type in ('clt', 'pj', 'sociedade', 'empresa', 'freelance', 'dividendos', 'aluguel', 'juros', 'outro')),
  expected_monthly numeric(14, 2) not null default 0,
  start_date date,
  end_date date,
  color text not null default '#8a00ff',
  notes text,
  active boolean not null default true,
  default_category_id bigint references public.categories (id) on delete set null,
  created_at timestamptz not null default now()
);

-- ---------- lançamentos ----------
create table public.transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  date date not null,
  amount numeric(14, 2) not null check (amount >= 0),
  type text not null check (type in ('expense', 'income', 'transfer')),
  description text not null default '',
  category_id bigint references public.categories (id) on delete set null,
  account_id bigint references public.accounts (id) on delete set null,
  to_account_id bigint references public.accounts (id) on delete set null,
  income_source_id bigint references public.income_sources (id) on delete set null,
  notes text,
  tags text[],
  import_hash text,
  created_at timestamptz not null default now()
);

-- ---------- investimentos ----------
create table public.investments (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null,
  type text not null check (type in ('acoes', 'fiis', 'renda_fixa', 'tesouro', 'cripto', 'fundos', 'previdencia', 'exterior', 'poupanca', 'outro')),
  institution text,
  ticker text,
  color text not null default '#8a00ff',
  notes text,
  archived boolean not null default false,
  created_at timestamptz not null default now()
);

create table public.investment_movements (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  investment_id bigint not null references public.investments (id) on delete cascade,
  date date not null,
  type text not null check (type in ('aporte', 'resgate', 'rendimento', 'dividendo')),
  amount numeric(14, 2) not null check (amount >= 0),
  notes text,
  created_at timestamptz not null default now()
);

create table public.investment_snapshots (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  investment_id bigint not null references public.investments (id) on delete cascade,
  date date not null,
  value numeric(14, 2) not null,
  created_at timestamptz not null default now(),
  unique (investment_id, date)
);

-- ---------- patrimônio (empresas, sociedades, bens, dívidas) ----------
create table public.assets (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null,
  type text not null check (type in ('empresa', 'sociedade', 'imovel', 'veiculo', 'outro_ativo', 'emprestimo', 'financiamento', 'cartao', 'outro_passivo')),
  kind text not null check (kind in ('ativo', 'passivo')),
  ownership_pct numeric(5, 2) check (ownership_pct is null or (ownership_pct >= 0 and ownership_pct <= 100)),
  color text not null default '#8a00ff',
  notes text,
  archived boolean not null default false,
  created_at timestamptz not null default now()
);

create table public.asset_valuations (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  asset_id bigint not null references public.assets (id) on delete cascade,
  date date not null,
  value numeric(16, 2) not null,
  created_at timestamptz not null default now(),
  unique (asset_id, date)
);

-- ---------- índices ----------
create index on public.accounts (user_id);
create index on public.categories (user_id);
create index on public.income_sources (user_id);
create index on public.income_sources (default_category_id);
create index on public.transactions (user_id, date desc);
create index on public.transactions (category_id);
create index on public.transactions (account_id);
create index on public.transactions (to_account_id);
create index on public.transactions (income_source_id);
create unique index transactions_user_import_hash_key on public.transactions (user_id, import_hash) where import_hash is not null;
create index on public.investments (user_id);
create index on public.investment_movements (user_id);
create index on public.investment_movements (investment_id);
create index on public.investment_snapshots (user_id);
create index on public.assets (user_id);
create index on public.asset_valuations (user_id);

-- ---------- segurança: RLS + permissões ----------
do $$
declare
  t text;
begin
  foreach t in array array[
    'accounts', 'categories', 'income_sources', 'transactions', 'investments',
    'investment_movements', 'investment_snapshots', 'assets', 'asset_valuations'
  ] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
    execute format(
      'create policy "owner_all" on public.%I for all to authenticated
         using (user_id = (select auth.uid()))
         with check (user_id = (select auth.uid()))',
      t
    );
  end loop;
end
$$;
